def _cell(ax, x, y, w, h, kind, text='', fs=11):
    """Time-step cell: 'in' (input), 'tgt' (target), 'gap' (skipped), 'off' (unused), 'ser' (series)."""
    style = {'in': (BLUE, 'tint', 1.4, '-'), 'tgt': (ORANGE, 'solid', 1.4, '-'),
             'gap': ('#9AA9B8', 'white', 1.0, (0, (2, 2))), 'off': ('#D5DEE7', 'white', .9, '-'),
             'ser': ('#8FA0B2', 'tint', 1.1, '-')}[kind]
    col, fill, lw, ls = style
    if kind == 'ser':
        box(ax, x, y, w, h, text, '#56687A', fill='tint', lw=lw, radius=.05, fs=fs, text_color=INK)
    else:
        box(ax, x, y, w, h, text, col, fill=fill, lw=lw, ls=ls, radius=.05, fs=fs)


