def _interval_models():
    """Quantile gradient boosting for 3-hour-ahead wind power; returns test predictions and actuals."""
    from sklearn.ensemble import HistGradientBoostingRegressor
    speed, p = wind_power()
    h, L = 3, 6
    n = len(p)
    idx = np.arange(L - 1, n - h)
    X = np.c_[[p[idx - j] for j in range(L)]].T
    hod = idx % 24
    X = np.c_[X, np.sin(2 * np.pi * hod / 24), np.cos(2 * np.pi * hod / 24)]
    y = p[idx + h]
    split = 24 * 90
    tr, te = idx + h < split, idx >= split          # purge: no training target after the split
    qs = [.05, .1, .25, .5, .75, .9, .95]
    preds = []
    for q in qs:
        m = HistGradientBoostingRegressor(loss='quantile', quantile=q, max_iter=250, learning_rate=.05,
                                          max_leaf_nodes=15, min_samples_leaf=30, random_state=0)
        m.fit(X[tr], y[tr])
        preds.append(m.predict(X[te]))
    P = np.sort(np.clip(np.array(preds).T, 0, 50), axis=1)
    return qs, P, y[te], idx[te] + h


