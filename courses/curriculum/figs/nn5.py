def hourly_load(days: int = 84, seed: int = 11):
    """Synthetic hourly electrical load (MW) with trend, daily and weekly cycles and AR(1) noise.

    Hour 0 is Monday 00:00. Returns (t_hours, load, components dict).
    """
    rng = np.random.default_rng(seed)
    n = days * 24
    t = np.arange(n)
    hod = t % 24
    dow = (t // 24) % 7
    weekend = dow >= 5

    def profile(h, shift=0.0, scale=1.0):
        return scale * (-95 * np.exp(-.5 * ((h - 3.5) / 2.6) ** 2)
                        + 55 * np.exp(-.5 * ((h - 8.5 - shift) / 2.0) ** 2)
                        + 30 * np.exp(-.5 * ((h - 13.5) / 3.0) ** 2)
                        + 95 * np.exp(-.5 * ((h - 19.0) / 2.2) ** 2))

    daily = np.where(weekend, profile(hod, shift=1.5, scale=.72), profile(hod))
    weekly = np.where(weekend, -55.0, 0.0)
    trend = 590 + .6 * t / 24 + 10 * np.sin(2 * np.pi * t / (24 * 63))
    e = np.zeros(n)
    eps = rng.normal(0, 7, n)
    for i in range(1, n):
        e[i] = .9 * e[i - 1] + eps[i]
    y = trend + daily + weekly + e
    return t, y, {'trend': trend, 'daily': daily, 'weekly': weekly, 'noise': e}


def moving_average_168(y):
    """Centred 2x168 moving average (the classical trend filter for an even period)."""
    w = np.r_[.5, np.ones(167), .5] / 168
    out = np.full(len(y), np.nan)
    out[84:-84] = np.convolve(y, w, mode='valid')
    return out


def decompose(y):
    """Classical additive decomposition with period 168 h: trend, seasonal, residual."""
    trend = moving_average_168(y)
    detr = y - trend
    how = np.arange(len(y)) % 168
    seas = np.array([np.nanmean(detr[how == k]) for k in range(168)])
    seas -= seas.mean()
    seasonal = seas[how]
    resid = y - trend - seasonal
    return trend, seasonal, resid


def acf(x, nlags):
    x = np.asarray(x, float)
    x = x[~np.isnan(x)]
    x = x - x.mean()
    d = np.dot(x, x)
    return np.array([1.0] + [np.dot(x[:-k], x[k:]) / d for k in range(1, nlags + 1)])


def wind_power(hours: int = 24 * 120, seed: int = 3, capacity: float = 50.0):
    """Synthetic hourly wind speed (m/s) and wind-farm power (MW) through a generic cubic power curve
    (cut-in 3 m/s, rated 12 m/s, no cut-out)."""
    rng = np.random.default_rng(seed)
    z = np.zeros(hours)
    for i in range(1, hours):
        z[i] = .97 * z[i - 1] + rng.normal(0, .24)
    daily = .12 * np.sin(2 * np.pi * (np.arange(hours) % 24 - 9) / 24)
    speed = 7.0 * np.exp(.5 * z + daily)
    p = capacity * np.clip((speed ** 3 - 27.0) / (12.0 ** 3 - 27.0), 0, 1)
    return speed, p


