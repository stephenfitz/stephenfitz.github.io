def _chain(ax, xs, y, color, w=.5, h=.42, texts=None, fs=12, fill='tint'):
    out = []
    for i, x in enumerate(xs):
        t = texts[i] if texts else ''
        out.append(box(ax, x - w / 2, y - h / 2, w, h, t, color, fill=fill, fs=fs, radius=.07))
    for a, b in zip(out[:-1], out[1:]):
        arrow(ax, a.r, b.l, color=INK, lw=1.4, head=10)
    return out


