def soft_alignment():
    hours_k = np.arange(-71, 1)                 # key times relative to the origin (00:00 of day D+1 minus 1 h)
    clock_k = (hours_k + 71) % 24               # clock hour of each key; first key is 00:00 of day D-2
    days_back = 2 - (hours_k + 71) // 24        # 2, 1, 0 for days D-2, D-1, D
    clock_q = np.arange(24)                     # tomorrow's hours
    beta, lam = 6.0, .8
    S = beta * np.cos(2 * np.pi * (clock_q[:, None] - clock_k[None, :]) / 24) - lam * days_back[None, :]
    W = np.exp(S - S.max(1, keepdims=True))
