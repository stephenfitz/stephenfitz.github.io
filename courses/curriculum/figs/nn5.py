@fig
def vanishing():
    rng = np.random.default_rng(4)
    H, T, reps = 32, 60, 30
    f, axs = half()
    ax = axs[0]
    results = {}
    for gain, col in [(.6, ORANGE), (1.0, BLUE), (1.6, TEAL)]:
        norms = np.zeros((reps, T))
        for r in range(reps):
            Q, _ = np.linalg.qr(rng.normal(size=(H, H)))
            W = gain * Q
            U = rng.normal(0, .25, (H, 4))
            h = np.zeros(H)
            hs = []
            for t in range(T):
                h = np.tanh(W @ h + U @ rng.normal(size=4))
                hs.append(h.copy())
            J = np.eye(H)
            norms[r, 0] = 1.0
            for k in range(1, T):
                hj = hs[T - k]
                J = J @ (np.diag(1 - hj ** 2) @ W)
                norms[r, k] = np.linalg.norm(J, 2)
        med = np.median(norms, axis=0)
        results[gain] = med
        ax.semilogy(np.arange(T), med, color=col, lw=2.4)
    ax.set_ylim(1e-12, 1e3)
    ax.set_xlim(0, 60)
    ax.text(24, results[.6][24] * 6, 'weight gain 0.6', color=ORANGE, fontsize=12.5, ha='left', fontweight='medium')
    ax.text(30, results[1.0][30] * 8, 'gain 1.0', color=BLUE, fontsize=12.5, ha='left', fontweight='medium')
    ax.text(30, results[1.6][30] * 6, 'gain 1.6', color=TEAL, fontsize=12.5, ha='left', fontweight='medium')
    ax.set_yticks([1e-12, 1e-9, 1e-6, 1e-3, 1, 1e3])
    ax.tick_params(axis='y', labelsize=13.5)
    clean(ax, 'Steps back in time k', r'Gradient size  $\Vert\partial h_T/\partial h_{T-k}\Vert$')
    save('nn5_vanishing', f, 'Computed Jacobian products for a tanh RNN with 32 units, orthogonal recurrent weights '
         'scaled by the gain, random inputs; median spectral norm over 30 runs (seed 4).', kind='computed')
    return {g: [float(v[10]), float(v[20]), float(v[40])] for g, v in results.items()}


