@fig
def error_accumulation():
    rng = np.random.default_rng(8)
    n = 7000
    phi1, phi2 = 1.2, -.5
    y = np.zeros(n)
    e = rng.normal(0, 1, n)
    for i in range(2, n):
        y[i] = phi1 * y[i - 1] + phi2 * y[i - 2] + e[i]
    tr, te = y[:5000], y[5000:]
    a1 = np.dot(tr[:-1], tr[1:]) / np.dot(tr[:-1], tr[:-1])
    X2 = np.c_[tr[1:-1], tr[:-2]]
    b2 = np.linalg.lstsq(X2, tr[2:], rcond=None)[0]
    H = 12
    direct = [np.dot(tr[:-h], tr[h:]) / np.dot(tr[:-h], tr[:-h]) for h in range(1, H + 1)]
    origins = np.arange(2, len(te) - H)
    rec1, dirr, rec2 = [], [], []
    for h in range(1, H + 1):
        tgt = te[origins + h]
        rec1.append(np.sqrt(np.mean((tgt - a1 ** h * te[origins]) ** 2)))
        dirr.append(np.sqrt(np.mean((tgt - direct[h - 1] * te[origins]) ** 2)))
        p1, p0 = te[origins].copy(), te[origins - 1].copy()
        for _ in range(h):
            p1, p0 = b2[0] * p1 + b2[1] * p0, p1
        rec2.append(np.sqrt(np.mean((tgt - p1) ** 2)))
    clim = np.sqrt(np.mean((te - tr.mean()) ** 2))
    hs = np.arange(1, H + 1)
    f, axs = half()
    ax = axs[0]
    ax.axhline(clim, color=GREY, lw=1.5, ls=(0, (2, 2)))
    ax.plot(hs, rec1, '-o', color=ORANGE, ms=5)
    ax.plot(hs, dirr, '-s', color=BLUE, ms=5)
    ax.plot(hs, rec2, '-^', color=TEAL, ms=5, lw=1.8)
    ax.text(5.3, max(rec1) + .04, 'recursive, one-lag model', color=ORANGE, fontsize=12.5, ha='left', va='bottom',
            fontweight='medium')
    ax.text(12.3, clim + .025, 'predict the\ntraining mean', color=GREY, fontsize=12, ha='right', va='bottom')
    note(ax, 6, dirr[5], 'direct, one-lag models', xytext=(6.4, 1.62), color=BLUE, fs=12.5, rad=.2)
    note(ax, 2, rec2[1], 'recursive, correct\ntwo-lag model', xytext=(3.3, 1.3), color=TEAL, fs=12.5, rad=-.2)
    ax.set_xlim(.6, 12.4)
    ax.set_ylim(.9, 2.3)
    ax.set_xticks(range(1, 13))
    clean(ax, 'Forecast horizon h (steps)', 'RMSE on test origins')
    save('nn5_error_accumulation', f, 'Simulated AR(2) process y_t = 1.2 y_t-1 - 0.5 y_t-2 + e_t (seed 8, unit noise); '
         'models fitted on the first 5,000 steps, RMSE on 1,986 later origins.', kind='computed')
    return {'a1': float(a1), 'b2': b2.tolist(), 'rec1': np.round(rec1, 3).tolist(), 'direct': np.round(dirr, 3).tolist(),
            'rec2': np.round(rec2, 3).tolist(), 'clim': float(clim), 'n_origins': int(len(origins))}


