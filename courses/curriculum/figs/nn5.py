def _sensor_data(seed: int = 5, n: int = 3000):
    rng = np.random.default_rng(seed)
    t = np.arange(n)
    e = np.zeros((n, 3))
    for i in range(1, n):
        e[i] = .8 * e[i - 1] + rng.normal(0, .25, 3)
    c1 = np.sin(2 * np.pi * t / 144) + e[:, 0]
    c2 = .8 * c1 + .6 * e[:, 1]
    c3 = .7 * np.sin(2 * np.pi * t / 50) + e[:, 2]
    X = np.c_[c1, c2, c3]
    events = [(2150, 2175, 'spikes on sensor 3'), (2480, 2560, 'sensors 1 and 2 decouple'),
              (2780, 2860, 'level shift on sensor 1')]
    a, b, _ = events[0]
    X[a:b, 2] += rng.choice([-2.5, 2.5], b - a) * (rng.random(b - a) < .5)
    a, b, _ = events[1]
    X[a:b, 1] = -.8 * X[a:b, 0] + .6 * e[a:b, 1]
    a, b, _ = events[2]
    X[a:b, 0] += 1.6
    return X, events


@fig
def recon_error():
    import torch
    from torch import nn
    torch.manual_seed(0)
    X, events = _sensor_data()
    mu, sd = X[:1500].mean(0), X[:1500].std(0)
    Z = ((X - mu) / sd).astype(np.float32)
    T = 24
    win = np.lib.stride_tricks.sliding_window_view(Z, (T, 3))[:, 0]      # (N, T, 3); window i ends at i+T-1
    ends = np.arange(len(win)) + T - 1
    train = win[ends < 1500]

    class AE(nn.Module):
        def __init__(self, f=3, h=16):
            super().__init__()
            self.enc = nn.LSTM(f, h, batch_first=True)
            self.dec = nn.LSTM(h, h, batch_first=True)
            self.out = nn.Linear(h, f)

        def forward(self, x):
            _, (h, _) = self.enc(x)
            rep = h[-1].unsqueeze(1).repeat(1, x.shape[1], 1)
            y, _ = self.dec(rep)
            return self.out(y)
    model = AE()
    opt = torch.optim.Adam(model.parameters(), lr=5e-3)
    xt = torch.tensor(train)
    g = torch.Generator().manual_seed(0)
    for epoch in range(40):
        perm = torch.randperm(len(xt), generator=g)
        for k in range(0, len(xt), 64):
            b = xt[perm[k:k + 64]]
            opt.zero_grad()
            loss = ((model(b) - b) ** 2).mean()
            loss.backward()
            opt.step()
    with torch.no_grad():
        allw = torch.tensor(win)
        err = ((model(allw) - allw) ** 2).mean(dim=(1, 2)).numpy()
    val = (ends >= 1500 + T) & (ends < 2000)
    thr = float(np.quantile(err[val], .99))
    test = ends >= 2000
    flag = test & (err > thr)
    in_event = np.zeros(len(ends), bool)
    for a, b, _ in events:
        in_event |= (ends >= a) & (ends - T + 1 < b)
    detected = [bool(np.any(flag & (ends >= a) & (ends - T + 1 < b))) for a, b, _ in events]
    false_windows = int(np.sum(flag & ~in_event))
    f, axs = plt.subplots(2, 1, figsize=(11.8, 4.5), sharex=True, layout='constrained',
                          gridspec_kw=dict(height_ratios=[1.15, 1]))
    a1, a2 = axs
    tt = np.arange(len(Z))
    view = tt >= 1500
    for k, (c, name) in enumerate(zip([BLUE, TEAL, PURPLE], ['sensor 1', 'sensor 2', 'sensor 3'])):
        a1.plot(tt[view], Z[view, k] + 5.2 - 2.9 * k, color=c, lw=.9)
        a1.text(1510 + 115 * k, 9.7, name, color=c, fontsize=11.5, va='center', fontweight='semibold')
    for (a, b, name) in events:
        for ax in axs:
            ax.axvspan(a, b, color=ORANGE_T, zorder=0)
        a1.text((a + b) / 2, 9.7, name, ha='center', fontsize=11.5, color=ORANGE)
    a1.axvline(2000, color=INK, lw=1.2, ls=(0, (3, 2)))
    a1.set_yticks([])
    a1.set_ylim(-5.6, 10.6)
    a1.spines['left'].set_visible(False)
    a1.text(1750, -5.1, 'validation period (normal)', ha='center', fontsize=11.5, color=TEAL)
    a1.text(2330, -5.1, 'test period', ha='center', fontsize=11.5, color=INK)
    e_view = ends >= 1500 + T
    a2.plot(ends[e_view], err[e_view], color=GREY, lw=1)
    a2.plot(ends[flag], err[flag], 'o', color=RED, ms=3)
    a2.axhline(thr, color=TEAL, lw=1.6, ls=(0, (4, 2)))
    a2.set_yscale('log')
    a2.set_yticks([.1, .3, 1, 3], ['0.1', '0.3', '1', '3'])
    a2.minorticks_off()
    a2.text(1510, thr * 1.25, 'threshold: 99th percentile of validation errors', color=TEAL, fontsize=11.5,
            va='bottom')
    a2.set_xlim(1500, 3000)
    clean(a2, 'Time step (window end)', 'Reconstruction\nerror')
    a2.yaxis.label.set_size(12.5)
    save('nn5_recon_error', f, 'Synthetic three-sensor series (seed 5) with three injected anomalies; LSTM autoencoder '
         '(hidden size 16, 24-step windows) trained on steps 0-1,499 (torch seed 0).', kind='computed')
    return {'thr': thr, 'detected': detected, 'false_windows': false_windows,
            'flagged': int(flag.sum()), 'test_windows': int(test.sum())}


